-- =========================================================
-- 6. ORDERS, PAYMENT AND SHIPPING
-- =========================================================

CREATE TABLE orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(50) NOT NULL UNIQUE,
    buyer_company_id BIGINT NOT NULL,
    placed_by BIGINT NOT NULL,
    checkout_key VARCHAR(100) NOT NULL,
    purchase_reference VARCHAR(100),

    company_name_snapshot VARCHAR(255) NOT NULL,
    tax_id_snapshot VARCHAR(100),
    shipping_address_snapshot JSON NOT NULL,
    billing_address_snapshot JSON NOT NULL,

    currency CHAR(3) NOT NULL DEFAULT 'USD',
    subtotal DECIMAL(18,2) NOT NULL,
    shipping_total DECIMAL(18,2) NOT NULL DEFAULT 0,
    grand_total DECIMAL(18,2) NOT NULL,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_orders_buyer_company
        FOREIGN KEY (buyer_company_id)
        REFERENCES companies(company_id),

    CONSTRAINT fk_orders_placed_by
        FOREIGN KEY (placed_by)
        REFERENCES users(user_id),

    CONSTRAINT uq_orders_placed_by_checkout_key
        UNIQUE (placed_by, checkout_key),

    CONSTRAINT chk_orders_currency
        CHECK (currency = 'USD'),

    CONSTRAINT chk_orders_nonnegative_totals
        CHECK (
            subtotal >= 0
            AND shipping_total >= 0
        ),

    CONSTRAINT chk_orders_grand_total
        CHECK (
            grand_total = subtotal + shipping_total
        )
);

CREATE INDEX idx_orders_buyer_company_created
    ON orders(buyer_company_id, created_at);


CREATE TABLE seller_orders (
    seller_order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    supplier_id BIGINT NOT NULL,

    supplier_name_snapshot VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'CONFIRMED',

    subtotal DECIMAL(18,2) NOT NULL,
    shipping_fee DECIMAL(18,2) NOT NULL DEFAULT 0,
    grand_total DECIMAL(18,2) NOT NULL,

    processing_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_seller_orders_order
        FOREIGN KEY (order_id)
        REFERENCES orders(order_id),

    CONSTRAINT fk_seller_orders_supplier
        FOREIGN KEY (supplier_id)
        REFERENCES suppliers(supplier_id),

    CONSTRAINT uq_seller_orders_order_supplier
        UNIQUE (order_id, supplier_id),

    CONSTRAINT chk_seller_orders_status
        CHECK (
            status IN (
                'CONFIRMED',
                'PROCESSING',
                'SHIPPED',
                'DELIVERED'
            )
        ),

    CONSTRAINT chk_seller_orders_nonnegative_totals
        CHECK (
            subtotal >= 0
            AND shipping_fee >= 0
        ),

    CONSTRAINT chk_seller_orders_grand_total
        CHECK (
            grand_total = subtotal + shipping_fee
        )
);

CREATE INDEX idx_seller_orders_supplier_status
    ON seller_orders(supplier_id, status);


CREATE TABLE order_items (
    order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_order_id BIGINT NOT NULL,
    listing_id BIGINT NOT NULL,

    product_name_snapshot VARCHAR(255) NOT NULL,
    part_number_snapshot VARCHAR(100) NOT NULL,
    seller_sku_snapshot VARCHAR(100) NOT NULL,
    condition_snapshot VARCHAR(20) NOT NULL,

    quantity INT NOT NULL,
    unit_price DECIMAL(18,2) NOT NULL,
    line_total DECIMAL(18,2) NOT NULL,

    CONSTRAINT fk_order_items_seller_order
        FOREIGN KEY (seller_order_id)
        REFERENCES seller_orders(seller_order_id),

    CONSTRAINT fk_order_items_listing
        FOREIGN KEY (listing_id)
        REFERENCES seller_listings(listing_id),

    CONSTRAINT uq_order_items_seller_order_listing
        UNIQUE (seller_order_id, listing_id),

    CONSTRAINT chk_order_items_values
        CHECK (
            quantity > 0
            AND unit_price >= 0
        ),

    CONSTRAINT chk_order_items_line_total
        CHECK (
            line_total = quantity * unit_price
        )
);


CREATE TABLE payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE,

    payment_method VARCHAR(30) NOT NULL DEFAULT 'SIMULATION',
    amount DECIMAL(18,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'SUCCEEDED',
    paid_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_payments_order
        FOREIGN KEY (order_id)
        REFERENCES orders(order_id),

    CONSTRAINT chk_payments_amount
        CHECK (amount >= 0),

    CONSTRAINT chk_payments_simulation
        CHECK (
            payment_method = 'SIMULATION'
            AND status = 'SUCCEEDED'
        )
);


CREATE TABLE shipments (
    shipment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_order_id BIGINT NOT NULL UNIQUE,

    carrier VARCHAR(100) NOT NULL,
    tracking_number VARCHAR(150),
    shipped_at TIMESTAMP NOT NULL,
    estimated_delivery_at TIMESTAMP,
    delivered_at TIMESTAMP,

    CONSTRAINT fk_shipments_seller_order
        FOREIGN KEY (seller_order_id)
        REFERENCES seller_orders(seller_order_id),

    CONSTRAINT uq_shipments_carrier_tracking
        UNIQUE (carrier, tracking_number),

    CONSTRAINT chk_shipments_delivery_time
        CHECK (
            delivered_at IS NULL
            OR delivered_at >= shipped_at
        )
);

-- =========================================================
-- 7. REVIEWS AND NOTIFICATIONS
-- =========================================================

CREATE TABLE reviews (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id BIGINT NOT NULL UNIQUE,
    reviewer_user_id BIGINT NOT NULL,
    product_rating INT NOT NULL,
    supplier_rating INT NOT NULL,
    comment TEXT,
    is_visible BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_reviews_order_item
        FOREIGN KEY (order_item_id)
        REFERENCES order_items(order_item_id),

    CONSTRAINT fk_reviews_reviewer
        FOREIGN KEY (reviewer_user_id)
        REFERENCES users(user_id),

    CONSTRAINT chk_reviews_product_rating
        CHECK (product_rating BETWEEN 1 AND 5),

    CONSTRAINT chk_reviews_supplier_rating
        CHECK (supplier_rating BETWEEN 1 AND 5)
);


CREATE TABLE notifications (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    message TEXT NOT NULL,
    action_path VARCHAR(500),
    read_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_notifications_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
);

CREATE INDEX idx_notifications_user_read_created
    ON notifications(user_id, read_at, created_at);