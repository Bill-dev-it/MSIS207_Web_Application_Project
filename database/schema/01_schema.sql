-- =========================================================
-- 4A. ENGINES AND RUL
-- =========================================================

CREATE TABLE engines (
    engine_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aircraft_id BIGINT NOT NULL,
    engine_model_id BIGINT NOT NULL,
    engine_code VARCHAR(80) NOT NULL,
    serial_number VARCHAR(100) NOT NULL,
    current_cycle BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_engines_aircraft
        FOREIGN KEY (aircraft_id)
        REFERENCES aircraft(aircraft_id),

    CONSTRAINT fk_engines_engine_model
        FOREIGN KEY (engine_model_id)
        REFERENCES engine_models(engine_model_id),

    CONSTRAINT uq_engines_aircraft_code
        UNIQUE (aircraft_id, engine_code),

    CONSTRAINT uq_engines_model_serial
        UNIQUE (engine_model_id, serial_number),

    CONSTRAINT chk_engines_current_cycle
        CHECK (current_cycle >= 0)
);


CREATE TABLE ml_model_versions (
    model_version_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_name VARCHAR(100) NOT NULL,
    version VARCHAR(80) NOT NULL,
    dataset_subset VARCHAR(30) NOT NULL,
    model_object_key VARCHAR(1024) NOT NULL,
    scaler_object_key VARCHAR(1024) NOT NULL,
    preprocessing_version VARCHAR(80) NOT NULL,
    window_size INT NOT NULL DEFAULT 30,
    sensor_schema JSON NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_ml_model_versions_name_version
        UNIQUE (model_name, version),

    CONSTRAINT chk_ml_model_versions_window_size
        CHECK (window_size > 0)
);



-- =========================================================
-- 4B. RUL PREDICTION PIPELINE
-- =========================================================

CREATE TABLE sensor_uploads (
    upload_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    engine_id BIGINT NOT NULL,
    uploaded_by BIGINT NOT NULL,
    original_file_name VARCHAR(255) NOT NULL,
    object_key VARCHAR(1024) NOT NULL,
    file_sha256 CHAR(64) NOT NULL,
    dataset_subset VARCHAR(30) NOT NULL,
    dataset_unit_id VARCHAR(80) NOT NULL,
    first_cycle BIGINT,
    last_cycle BIGINT,
    row_count INT,
    is_demo BOOLEAN NOT NULL DEFAULT TRUE,
    status VARCHAR(20) NOT NULL DEFAULT 'UPLOADED',
    validation_error TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_sensor_uploads_engine
        FOREIGN KEY (engine_id)
        REFERENCES engines(engine_id),

    CONSTRAINT fk_sensor_uploads_uploaded_by
        FOREIGN KEY (uploaded_by)
        REFERENCES users(user_id),

    CONSTRAINT chk_sensor_uploads_status
        CHECK (status IN ('UPLOADED', 'VALID', 'INVALID')),

    CONSTRAINT chk_sensor_uploads_cycle_range
        CHECK (
            first_cycle IS NULL
            OR last_cycle IS NULL
            OR last_cycle >= first_cycle
        ),

    CONSTRAINT chk_sensor_uploads_row_count
        CHECK (
            row_count IS NULL
            OR row_count > 0
        )
);

CREATE INDEX idx_sensor_uploads_engine_created
    ON sensor_uploads(engine_id, created_at);


CREATE TABLE rul_predictions (
    prediction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    upload_id BIGINT NOT NULL,
    model_version_id BIGINT NOT NULL,
    requested_by BIGINT NOT NULL,
    request_key VARCHAR(100) NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL DEFAULT 'RUNNING',
    predicted_rul DECIMAL(12,3),
    cycle_at_prediction BIGINT,
    urgency VARCHAR(20),
    decision_rule_snapshot JSON NOT NULL,
    recommendation_config_snapshot JSON,
    recommendation_status VARCHAR(20) NOT NULL DEFAULT 'NOT_RUN',
    explanation TEXT,
    error_message TEXT,
    prediction_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP,

    CONSTRAINT fk_rul_predictions_upload
        FOREIGN KEY (upload_id)
        REFERENCES sensor_uploads(upload_id),

    CONSTRAINT fk_rul_predictions_model_version
        FOREIGN KEY (model_version_id)
        REFERENCES ml_model_versions(model_version_id),

    CONSTRAINT fk_rul_predictions_requested_by
        FOREIGN KEY (requested_by)
        REFERENCES users(user_id),

    CONSTRAINT chk_rul_predictions_status
        CHECK (
            status IN ('RUNNING', 'SUCCEEDED', 'FAILED')
        ),

    CONSTRAINT chk_rul_predictions_predicted_rul
        CHECK (
            predicted_rul IS NULL
            OR predicted_rul >= 0
        ),

    CONSTRAINT chk_rul_predictions_urgency
        CHECK (
            urgency IS NULL
            OR urgency IN (
                'NORMAL',
                'MONITOR',
                'PREPARE',
                'PRIORITIZE'
            )
        ),

    CONSTRAINT chk_rul_predictions_success_fields
        CHECK (
            status <> 'SUCCEEDED'
            OR (
                predicted_rul IS NOT NULL
                AND cycle_at_prediction IS NOT NULL
                AND urgency IS NOT NULL
                AND completed_at IS NOT NULL
            )
        ),

    CONSTRAINT chk_rul_predictions_recommendation_status
        CHECK (
            recommendation_status IN (
                'NOT_RUN',
                'READY',
                'NO_MATCH',
                'FAILED'
            )
        )
);

CREATE INDEX idx_rul_predictions_upload_date
    ON rul_predictions(upload_id, prediction_date);


CREATE TABLE replacement_recommendations (
    recommendation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prediction_id BIGINT NOT NULL,
    listing_id BIGINT NOT NULL,
    rank_position INT NOT NULL,
    ranking_score DECIMAL(12,6) NOT NULL,
    reason TEXT NOT NULL,
    listing_snapshot JSON NOT NULL,

    CONSTRAINT fk_replacement_recommendations_prediction
        FOREIGN KEY (prediction_id)
        REFERENCES rul_predictions(prediction_id),

    CONSTRAINT fk_replacement_recommendations_listing
        FOREIGN KEY (listing_id)
        REFERENCES seller_listings(listing_id),

    CONSTRAINT uq_recommendations_prediction_listing
        UNIQUE (prediction_id, listing_id),

    CONSTRAINT uq_recommendations_prediction_rank
        UNIQUE (prediction_id, rank_position),

    CONSTRAINT chk_recommendations_rank_position
        CHECK (rank_position > 0)
);



