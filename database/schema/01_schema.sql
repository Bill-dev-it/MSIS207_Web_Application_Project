-- =========================================================
-- 1. ACCOUNTS & ORGANIZATIONS
-- =========================================================

CREATE TABLE companies (
    company_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name VARCHAR(255) NOT NULL,
    company_type VARCHAR(30) NOT NULL,
    tax_id VARCHAR(100),
    country_code CHAR(2) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_companies_company_type
        CHECK (
            company_type IN (
                'AIRLINE',
                'MRO',
                'SUPPLIER',
                'MIXED',
                'PLATFORM'
            )
        )
);


CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_users_company
        FOREIGN KEY (company_id)
        REFERENCES companies(company_id),

    CONSTRAINT chk_users_role
        CHECK (
            role IN ('BUYER', 'SUPPLIER', 'ADMIN')
        )
);


CREATE TABLE addresses (
    address_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    recipient_name VARCHAR(150) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    address_line VARCHAR(500) NOT NULL,
    city VARCHAR(100) NOT NULL,
    region VARCHAR(100),
    postal_code VARCHAR(20),
    country_code CHAR(2) NOT NULL,

    CONSTRAINT fk_addresses_company
        FOREIGN KEY (company_id)
        REFERENCES companies(company_id)
);


CREATE TABLE suppliers (
    supplier_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL UNIQUE,
    store_name VARCHAR(150) NOT NULL,
    slug VARCHAR(150) NOT NULL UNIQUE,
    description TEXT,
    logo_object_key VARCHAR(1024),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_suppliers_company
        FOREIGN KEY (company_id)
        REFERENCES companies(company_id),

    CONSTRAINT chk_suppliers_status
        CHECK (
            status IN ('PENDING', 'APPROVED', 'SUSPENDED')
        )
);


-- =========================================================
-- 2. CATALOG AND STOCK
-- =========================================================

CREATE TABLE categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL UNIQUE,
    slug VARCHAR(150) NOT NULL UNIQUE,
    description TEXT
);


CREATE TABLE engine_models (
    engine_model_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manufacturer VARCHAR(150) NOT NULL,
    model_name VARCHAR(150) NOT NULL,
    engine_family VARCHAR(100),
    engine_type VARCHAR(50),

    CONSTRAINT uq_engine_models_manufacturer_model
        UNIQUE (manufacturer, model_name)
);


CREATE TABLE products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL,
    product_name VARCHAR(255) NOT NULL,
    manufacturer VARCHAR(150) NOT NULL,
    part_number VARCHAR(100) NOT NULL,
    product_type VARCHAR(20) NOT NULL,
    description TEXT,
    technical_specs JSON,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_products_category
        FOREIGN KEY (category_id)
        REFERENCES categories(category_id),

    CONSTRAINT uq_products_manufacturer_part
        UNIQUE (manufacturer, part_number),

    CONSTRAINT chk_products_product_type
        CHECK (
            product_type IN ('ENGINE', 'MODULE', 'COMPONENT')
        )
);

CREATE INDEX idx_products_part_number
    ON products(part_number);


CREATE TABLE product_images (
    image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    object_key VARCHAR(1024) NOT NULL,
    alt_text VARCHAR(255),
    sort_order INT NOT NULL DEFAULT 0,

    CONSTRAINT fk_product_images_product
        FOREIGN KEY (product_id)
        REFERENCES products(product_id),

    CONSTRAINT uq_product_images_product_sort
        UNIQUE (product_id, sort_order)
);


CREATE TABLE product_engine_compatibility (
    product_id BIGINT NOT NULL,
    engine_model_id BIGINT NOT NULL,
    evidence_reference TEXT NOT NULL,
    is_demo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_product_engine_compatibility
        PRIMARY KEY (product_id, engine_model_id),

    CONSTRAINT fk_compatibility_product
        FOREIGN KEY (product_id)
        REFERENCES products(product_id),

    CONSTRAINT fk_compatibility_engine_model
        FOREIGN KEY (engine_model_id)
        REFERENCES engine_models(engine_model_id)
);

CREATE INDEX idx_compatibility_engine_model
    ON product_engine_compatibility(engine_model_id);


CREATE TABLE seller_listings (
    listing_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    seller_sku VARCHAR(100) NOT NULL,
    condition VARCHAR(20) NOT NULL,
    price DECIMAL(18,2) NOT NULL,
    stock_quantity INT NOT NULL DEFAULT 0,
    lead_time_days INT NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_seller_listings_supplier
        FOREIGN KEY (supplier_id)
        REFERENCES suppliers(supplier_id),

    CONSTRAINT fk_seller_listings_product
        FOREIGN KEY (product_id)
        REFERENCES products(product_id),

    CONSTRAINT uq_seller_listings_supplier_sku
        UNIQUE (supplier_id, seller_sku),

    CONSTRAINT chk_seller_listings_nonnegative
        CHECK (
            price >= 0
            AND stock_quantity >= 0
            AND lead_time_days >= 0
        ),

    CONSTRAINT chk_seller_listings_condition
        CHECK (
            condition IN ('NEW', 'USED', 'REFURBISHED')
        ),

    CONSTRAINT chk_seller_listings_status
        CHECK (
            status IN ('DRAFT', 'ACTIVE', 'HIDDEN')
        )
);
    -- Index không phải table và không chứa business data mới. 
    -- Nó giúp PostgreSQL tìm kiếm nhanh hơn khi backend sau này query kiểu:
    -- SELECT *
    -- FROM products
    -- WHERE part_number = '...';
CREATE INDEX idx_seller_listings_product_status_price
    ON seller_listings(product_id, status, price);


