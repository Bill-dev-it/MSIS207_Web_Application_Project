-- =========================================================
-- Runtime extensions for Buyer / Admin portals
-- Run AFTER 01_schema.sql. Idempotent (IF NOT EXISTS).
-- Adds only what 01_schema.sql lacks:
--   * audit_logs            – who did what, when (moderation, auth, orders)
--   * moderation_decisions  – approve / reject of DRAFT seller_listings
--   * supplier_inquiries    – buyer → supplier contact requests
--   * service_health_checks – results of Admin "RUL Health Check"
-- =========================================================

CREATE TABLE IF NOT EXISTS audit_logs (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT,
    action VARCHAR(60) NOT NULL,
    entity_type VARCHAR(60) NOT NULL,
    entity_id VARCHAR(60),
    metadata JSON,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_audit_logs_actor
        FOREIGN KEY (actor_user_id) REFERENCES users(user_id)
);

CREATE INDEX IF NOT EXISTS idx_audit_logs_entity
    ON audit_logs(entity_type, entity_id, created_at);


CREATE TABLE IF NOT EXISTS moderation_decisions (
    decision_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL,
    decision VARCHAR(10) NOT NULL,
    note TEXT,
    decided_by BIGINT NOT NULL,
    decided_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_moderation_listing
        FOREIGN KEY (listing_id) REFERENCES seller_listings(listing_id),
    CONSTRAINT fk_moderation_decided_by
        FOREIGN KEY (decided_by) REFERENCES users(user_id),
    CONSTRAINT chk_moderation_decision
        CHECK (decision IN ('APPROVED', 'REJECTED'))
);

CREATE INDEX IF NOT EXISTS idx_moderation_listing
    ON moderation_decisions(listing_id, decided_at);


CREATE TABLE IF NOT EXISTS supplier_inquiries (
    inquiry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_company_id BIGINT NOT NULL,
    created_by BIGINT NOT NULL,
    supplier_id BIGINT NOT NULL,
    seller_order_id BIGINT,
    subject VARCHAR(200) NOT NULL,
    message TEXT NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'OPEN',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_inquiries_company
        FOREIGN KEY (buyer_company_id) REFERENCES companies(company_id),
    CONSTRAINT fk_inquiries_user
        FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_inquiries_supplier
        FOREIGN KEY (supplier_id) REFERENCES suppliers(supplier_id),
    CONSTRAINT fk_inquiries_seller_order
        FOREIGN KEY (seller_order_id) REFERENCES seller_orders(seller_order_id),
    CONSTRAINT chk_inquiries_status
        CHECK (status IN ('OPEN', 'CLOSED'))
);

CREATE INDEX IF NOT EXISTS idx_inquiries_company
    ON supplier_inquiries(buyer_company_id, created_at);


CREATE TABLE IF NOT EXISTS service_health_checks (
    check_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_name VARCHAR(60) NOT NULL,
    status VARCHAR(10) NOT NULL,
    latency_ms INT,
    detail TEXT,
    checked_by BIGINT,
    checked_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_health_checked_by
        FOREIGN KEY (checked_by) REFERENCES users(user_id),
    CONSTRAINT chk_health_status
        CHECK (status IN ('UP', 'DOWN', 'DEGRADED'))
);

CREATE INDEX IF NOT EXISTS idx_health_service_time
    ON service_health_checks(service_name, checked_at);
