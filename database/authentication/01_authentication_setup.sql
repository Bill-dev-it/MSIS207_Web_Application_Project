-- AeroRUL / Authentication Batch 1
-- Run ONCE against the existing aircraft_marketplace PostgreSQL database.
-- Migration is transactional and does not modify existing rows.
-- Source schema: database/schema/01_schema.sql

BEGIN;

ALTER TABLE public.users
    ADD COLUMN IF NOT EXISTS email_verified_at TIMESTAMPTZ;

-- When the value changes, previously issued JWT sessions can be rejected.
ALTER TABLE public.users
    ADD COLUMN IF NOT EXISTS auth_version INTEGER NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS public.account_tokens (
    token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    purpose VARCHAR(20) NOT NULL,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_account_tokens_user
        FOREIGN KEY (user_id) REFERENCES public.users(user_id) ON DELETE CASCADE,
    CONSTRAINT chk_account_tokens_purpose
        CHECK (purpose IN ('EMAIL_VERIFY', 'PASSWORD_RESET')),
    CONSTRAINT chk_account_tokens_hash_format
        CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT chk_account_tokens_expiry
        CHECK (expires_at > created_at)
);

CREATE INDEX IF NOT EXISTS idx_account_tokens_user_purpose
    ON public.account_tokens (user_id, purpose, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_account_tokens_expiry
    ON public.account_tokens (expires_at);

COMMENT ON TABLE public.account_tokens IS
    'One-time email verification and password recovery tokens; stores only SHA-256 token digests, not raw tokens or JWTs.';
COMMENT ON COLUMN public.users.auth_version IS
    'Authentication version checked against the JWT; increment to revoke existing sessions after password reset.';

COMMIT;
